	public boolean hasWeakness(Actor opponent, MagicSpell activeSpell)
	{
		if (opponent == null)
		{
			return false;
		}
		NPC npc = (NPC) opponent;
		String npcName = npc.getName();
		if (npcName == null)
		{
			return false;
		}
		if (!ids.contains(npc.getId()))
		{
			return false;
		}
		return Objects.equals(activeSpell.getElement(), element);
	}
